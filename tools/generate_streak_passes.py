"""Generate Iris's ordered compute entry points; shared logic lives in kinoStreak.glsl."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for world, define in (("world0", "OVERWORLD"), ("world-1", "NETHER"), ("world1", "END")):
    stages = [("STREAK_DOWN", i) for i in range(10)] + [("STREAK_UP", i) for i in reversed(range(10))]
    for index, (direction, level) in enumerate(stages):
        suffix = "" if index == 0 else "_" + chr(ord("a") + index - 1)
        path = ROOT / "shaders" / world / f"composite3{suffix}.csh"
        content = (f"#version 430\n#define {define}\n#define COMPOSITE3\n"
                   f"#define {direction}\n#define STREAK_LEVEL {level}\n"
                   f"#define STREAK_DISPATCH_SCALE {2 ** -(level + 1):.10f}\n\n"
                   '#include "/program/kinoStreak.glsl"\n')
        if path.exists():
            # Refuse to overwrite unexpected/manual entry point changes.
            assert path.read_text(encoding="utf-8") == content, path
        else:
            path.write_text(content, encoding="utf-8")
        # Remove only exact entry points previously generated by this script.
        # They must not keep running after world blur as a second chain.
        old_path = ROOT / "shaders" / world / f"composite5{suffix}.csh"
        if old_path.exists():
            assert old_path.read_text(encoding="utf-8") == content.replace("#define COMPOSITE3", "#define COMPOSITE5"), old_path
            assert old_path.resolve().parent == (ROOT / "shaders" / world).resolve()
            assert old_path.name == f"composite5{suffix}.csh"
            print("Removing verified old post-blur generated stage:", old_path.resolve())
            old_path.unlink()
print("Verified/generated 60 KinoStreak compute entry points across all three dimensions.")
